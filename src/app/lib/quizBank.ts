function mix(seed: number) {
  let state = seed >>> 0 || 1;
  return () => {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

function present(question: RawQuestion, seed: number): QuizQuestion {
  const random = mix(seed);
  const options = [...question.options];
  const correct = options[0];
  for (let index = options.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    const current = options[index];
    options[index] = options[swap];
    options[swap] = current;
  }
  return {
    prompt: question.prompt,
    options,
    answer: options.indexOf(correct),
    why: question.why,
  };
}

export function dailyQuizQuestions(now = Date.now()): QuizQuestion[] {
  const day = riyadhDayIndex(now);
  const sets = Math.floor(BANK.length / PER_DAY);
  const start = (day % sets) * PER_DAY;
  return BANK.slice(start, start + PER_DAY).map((question, index) => present(question, day * 97 + index * 13 + 1));
}

export const QUIZ_BANK_DAYS = Math.floor(BANK.length / PER_DAY);
