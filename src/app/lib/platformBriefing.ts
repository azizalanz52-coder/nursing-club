function withClubColors(value: string) {
  return String(value || '')
    .replace(/NURSS\s*•\s*عنابي وذهبي/g, 'بني وذهبي')
    .replace(/NURSS • اللونان الرسميان العنابي والذهبي/g, 'بني وذهبي')
    .replace(/عنابي وذهبي/g, 'بني وذهبي')
    .replace(/العنابي والذهبي/g, 'البني والذهبي')
    .replace(/عنابي/g, 'بني');
}

export function normalizePlatformBriefing(raw?: Partial<PartnershipProposal> | null): PartnershipProposal {
  const base = DEFAULT_PLATFORM_BRIEFING;
  if (!raw) return structuredClone(base);
  const sections = Array.isArray(raw.sections) && raw.sections.length ? raw.sections : base.sections;
  return {
    ...base,
    ...raw,
    coverBadge: withClubColors(raw.coverBadge ?? base.coverBadge),
    coverTitle: withClubColors(raw.coverTitle ?? base.coverTitle),
    coverLead: withClubColors(raw.coverLead ?? base.coverLead),
    coverSub: withClubColors(raw.coverSub ?? base.coverSub),
    metaFrom: withClubColors(raw.metaFrom ?? base.metaFrom),
    metaTo: withClubColors(raw.metaTo ?? base.metaTo),
    metaSite: withClubColors(raw.metaSite ?? base.metaSite),
    metaSocial: withClubColors(raw.metaSocial ?? base.metaSocial),
    tocTitle: withClubColors(raw.tocTitle ?? base.tocTitle),
    tocIntro: withClubColors(raw.tocIntro ?? base.tocIntro),
    contactTitle: withClubColors(raw.contactTitle ?? base.contactTitle),
    contactBody: withClubColors(raw.contactBody ?? base.contactBody),
    nextStep: withClubColors(raw.nextStep ?? base.nextStep),
    footerNote: withClubColors(raw.footerNote ?? base.footerNote),
    sections: sections.map((section) => ({
      id: section.id || `s-${Date.now()}`,
      kicker: withClubColors(section.kicker || ''),
      title: withClubColors(section.title || ''),
      intro: withClubColors(section.intro || ''),
      paragraphs: Array.isArray(section.paragraphs) ? section.paragraphs.map(withClubColors) : [],
      callout: withClubColors(section.callout || ''),
      outro: withClubColors(section.outro || ''),
      cards: Array.isArray(section.cards)
        ? section.cards.map((card) => ({ title: withClubColors(card.title), body: withClubColors(card.body) }))
        : [],
      tableHeaders: Array.isArray(section.tableHeaders) ? section.tableHeaders.map(withClubColors) : undefined,
      tableRows: Array.isArray(section.tableRows)
        ? section.tableRows.map((row) => row.map(withClubColors))
        : undefined,
      steps: Array.isArray(section.steps) ? section.steps.map(withClubColors) : undefined,
    })),
  };
}

export function printPlatformBriefing(proposal: PartnershipProposal) {
  printClubBriefing(proposal, [
    { label: 'الجهة', value: proposal.metaFrom },
    { label: 'المنصة', value: proposal.metaSite },
    { label: 'الهوية', value: proposal.metaSocial },
    { label: 'الغرض', value: proposal.metaTo },
  ]);
}
